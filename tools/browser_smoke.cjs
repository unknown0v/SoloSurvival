const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:false,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const context = await browser.newContext({viewport:{width:960,height:540}});
  const page = await context.newPage();
  const errors = [];
  await page.addInitScript(() => {window.__pointerMoves=[];window.addEventListener('pointermove',e=>{window.__pointerMoves.push({x:e.clientX,y:e.clientY,dx:e.movementX,dy:e.movementY,locked:!!document.pointerLockElement});if(window.__pointerMoves.length>8)window.__pointerMoves.shift();});});
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => {
    const text = msg.text();
    if (/SCRIPT ERROR:|Parse Error:|ERROR:.*(shader|script|resource)/i.test(text)) errors.push(text);
    if (text.includes('SOLOSURVIVAL')) console.log(text);
  });
  try {
    await page.goto(process.env.GAME_URL || 'http://127.0.0.1:8060/index.html',{waitUntil:'domcontentloaded'});
    await page.waitForFunction(() => window.__soloSurvivalState?.ready,null,{timeout:120000});
    assert.ok((await page.evaluate(() => window.__soloSurvivalState.nodes))>100);
    const bounds = await page.locator('#canvas').boundingBox();
    const center = {x:bounds.x+bounds.width/2,y:bounds.y+bounds.height/2};
    await page.mouse.move(center.x,center.y);
    await page.waitForTimeout(500);
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => window.__soloSurvivalState.playing);
    await page.waitForTimeout(1800);
    console.log('BEFORE_GATHER '+JSON.stringify(await page.evaluate(() => window.__soloSurvivalState)));
    // The guaranteed tree is directly in front of the initial camera.
    await page.mouse.down();
    await page.waitForTimeout(180);
    await page.mouse.up();
    await page.waitForTimeout(900);
    await page.mouse.down();
    await page.waitForTimeout(180);
    await page.mouse.up();
    console.log('AFTER_GATHER '+JSON.stringify(await page.evaluate(() => window.__soloSurvivalState)));
    await page.waitForFunction(() => window.__soloSurvivalState.wood>0,null,{timeout:15000});
    const before = await page.evaluate(() => window.__soloSurvivalState);
    await page.keyboard.down('KeyD');
    await page.waitForFunction(x => Math.abs(window.__soloSurvivalState.position[0]-x)>1.5,before.position[0],{timeout:30000});
    await page.keyboard.up('KeyD');
    await page.waitForTimeout(400);
    const after = await page.evaluate(() => window.__soloSurvivalState);
    assert.ok(Math.abs(after.position[0]-before.position[0])>1,'Keyboard movement changes position');
    assert.ok(after.position[1]>after.ground-1 && after.position[1]<after.ground+3,'World collision holds');
    await page.keyboard.press('Tab');
    await page.waitForFunction(() => window.__soloSurvivalState.menu);
    await page.keyboard.press('Tab');
    await page.waitForFunction(() => !window.__soloSurvivalState.menu);
    await page.keyboard.press('F5');
    await page.waitForFunction(() => window.__soloSurvivalState.saves>0);
    const saved = await page.evaluate(() => window.__soloSurvivalState);
    await page.screenshot({path:'build/browser-smoke.png'});
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(() => window.__soloSurvivalState?.ready,null,{timeout:120000});
    const restored = await page.evaluate(() => window.__soloSurvivalState);
    assert.ok(restored.wood>=saved.wood,'Inventory restored across browser reload');
    assert.ok(Math.abs(restored.position[0]-saved.position[0])<0.5,'Position restored across browser reload');
    assert.deepEqual(errors,[],'No script/runtime errors');
    console.log('BROWSER_SMOKE_PASS '+JSON.stringify({wood:saved.wood,savedPosition:saved.position,restoredPosition:restored.position}));
    let pointerX=480,pointerY=270;
    const state = () => page.evaluate(() => window.__soloSurvivalState);
    async function clickUI(prefix) {
      await page.waitForFunction(prefix=>Object.keys(window.__soloSurvivalState?.ui?.buttons||{}).some(k=>k.startsWith(prefix)),prefix,{timeout:30000});
      const info = await page.evaluate(prefix => {
        const s=window.__soloSurvivalState;
        const key=Object.keys(s.ui.buttons).find(k=>k.startsWith(prefix));
        return key ? {point:s.ui.buttons[key],size:s.ui.size,key} : null;
      },prefix);
      assert.ok(info,'Visible UI button: '+prefix);
      const canvas=await page.locator('#canvas').boundingBox();
      pointerX=canvas.x+info.point[0]/info.size[0]*canvas.width;
      pointerY=canvas.y+info.point[1]/info.size[1]*canvas.height;
      await page.mouse.click(pointerX,pointerY);
      await page.waitForTimeout(400);
    }
    async function attack() {
      await page.mouse.down(); await page.waitForTimeout(180); await page.mouse.up();
      await page.waitForTimeout(800);
    }
    async function aimAt(point) {
      const s=await state();
      const dx=point[0]-s.position[0],dy=point[1]-(s.position[1]+1.65),dz=point[2]-s.position[2];
      const yaw=Math.atan2(-dx,-dz),pitch=Math.atan2(dy,Math.hypot(dx,dz));
      const delta=((yaw-s.yaw+Math.PI*3)%(Math.PI*2))-Math.PI;
      pointerX-=delta/0.002; pointerY-=(pitch-s.pitch)/0.002;
      await page.mouse.move(pointerX,pointerY,{steps:4});
      await page.waitForTimeout(700);
    }
    // A valid M1 item/save fixture is imported through the shipped file-picker UI.
    // No game mutation command or test-only runtime bridge is used.
    const fixture=JSON.parse(JSON.parse(fs.readFileSync('build/milestone1-fixture.json','utf8')).payload);
    const chooserPromise=page.waitForEvent('filechooser',{timeout:15000});
    await clickUI('RESTORE SAVE BACKUP');
    await (await chooserPromise).setFiles('build/milestone1-fixture.json');
    await page.waitForFunction(p => window.__soloSurvivalState?.ready && Math.abs(window.__soloSurvivalState.position[0]-p[0])<0.1 && Math.abs(window.__soloSurvivalState.position[2]-p[2])<0.1,fixture.position,{timeout:120000});
    await page.mouse.move(480,270); pointerX=480; pointerY=270;
    await page.keyboard.press('Enter');
    await page.waitForFunction(()=>window.__soloSurvivalState.playing);
    await page.keyboard.press('Tab');
    await page.waitForFunction(()=>window.__soloSurvivalState.menu);
    await clickUI('Building plan');
    await page.waitForFunction(()=>window.__soloSurvivalState.inventory.some(s=>s.id==='building_plan'),null,{timeout:30000});
    await clickUI('Building hammer');
    await page.waitForFunction(()=>window.__soloSurvivalState.inventory.some(s=>s.id==='hammer'),null,{timeout:45000});
    await page.mouse.move(480,270); pointerX=480; pointerY=270;
    await page.keyboard.press('Tab');
    await page.waitForFunction(()=>!window.__soloSurvivalState.menu);
    await page.keyboard.press('KeyB');
    await page.keyboard.press('Digit1');
    await page.waitForFunction(()=>window.__soloSurvivalState.building && window.__soloSurvivalState.placement==='',null,{timeout:15000});
    await attack();
    await page.waitForFunction(()=>window.__soloSurvivalState.structures===1);
    let base=(await state()).structure_data.find(p=>p.kind==='foundation');
    const baseCenter=[base.cell[0]*3,base.y,base.cell[1]*3];
    await aimAt(baseCenter);
    await page.keyboard.press('Digit5');
    await page.waitForFunction(()=>window.__soloSurvivalState.build_kind==='doorframe' && window.__soloSurvivalState.placement==='');
    await attack();
    await page.waitForFunction(()=>window.__soloSurvivalState.structures===2);
    await page.keyboard.press('Digit6');
    await page.waitForFunction(()=>window.__soloSurvivalState.build_kind==='door' && window.__soloSurvivalState.placement==='');
    await attack();
    await page.waitForFunction(()=>window.__soloSurvivalState.structures===3);
    await page.keyboard.press('KeyB');
    // Approach in observed short steps; leave space for the center deployable.
    // Continuous hold + low software-renderer FPS can overshoot between reports.
    await aimAt([baseCenter[0],baseCenter[1]+1.65,baseCenter[2]-2]);
    for(let step=0;step<8;step++) {
      const walking=await state();
      if(walking.position[2]<baseCenter[2]+2.65) break;
      await page.keyboard.down('KeyW');
      await page.waitForFunction(z=>window.__soloSurvivalState.position[2]<z-0.15,walking.position[2],{timeout:12000});
      await page.keyboard.up('KeyW');
      await page.waitForTimeout(600);
    }
    assert.ok((await state()).position[2]>baseCenter[2]+0.9,'Leave the deployable socket clear');
    await aimAt([baseCenter[0],baseCenter[1]+1.1,baseCenter[2]-1.5]);
    await page.keyboard.press('KeyE');
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='door'&&p.open));
    await aimAt([baseCenter[0]-0.59,baseCenter[1]+1.15,baseCenter[2]-0.91]);
    await page.keyboard.press('KeyE');
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='door'&&!p.open));
    await aimAt([baseCenter[0],baseCenter[1]+1.1,baseCenter[2]-1.5]);
    await page.keyboard.press('Digit3'); // crafted hammer is in slot 3
    await page.keyboard.press('KeyU');
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='door'&&p.tier===1));
    // Storage on this platform, keeping the player outside its collision box.
    await aimAt(baseCenter);
    await page.keyboard.press('KeyB'); await page.keyboard.press('Digit7');
    await page.waitForFunction(()=>window.__soloSurvivalState.build_kind==='storage' && window.__soloSurvivalState.placement==='');
    await attack();
    await page.waitForFunction(()=>window.__soloSurvivalState.structures===4);
    await page.keyboard.press('KeyB');
    await aimAt([baseCenter[0],baseCenter[1]+0.38,baseCenter[2]]);
    await page.keyboard.press('KeyE');
    await page.waitForFunction(()=>window.__soloSurvivalState.station!=='');
    await clickUI('DEPOSIT ALL THAT FITS');
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='storage' && p.inventory.some(s=>s.id==='ore'&&s.count===40)));
    await page.keyboard.press('Tab');
    await page.keyboard.press('F5');
    await page.waitForTimeout(500);
    const built=await state();
    await page.screenshot({path:'build/construction-smoke.png'});
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>window.__soloSurvivalState?.ready,null,{timeout:120000});
    const loaded=await state();
    assert.equal(loaded.structures,4,'Constructed shelter and storage restore');
    assert.ok(loaded.structure_data.some(p=>p.kind==='door'&&p.tier===1&&!p.open),'Door tier/state restore');
    assert.ok(loaded.structure_data.some(p=>p.kind==='storage'&&p.inventory.some(s=>s.id==='ore'&&s.count===40)),'Stored inventory restores');
    assert.deepEqual(errors,[],'No construction/runtime errors');
    console.log('CONSTRUCTION_BROWSER_PASS '+JSON.stringify({structures:loaded.structures,fixtureVersion:fixture.version,doorTier:1,storedOre:40,savedPosition:built.position}));
    await page.mouse.move(480,270); pointerX=480; pointerY=270;
    await page.keyboard.press('Enter');
    await page.waitForFunction(()=>window.__soloSurvivalState.playing);
    await aimAt([baseCenter[0],baseCenter[1]+0.38,baseCenter[2]]);
    await page.keyboard.press('KeyE');
    await page.waitForFunction(()=>window.__soloSurvivalState.station!=='');
    await clickUI('TAKE ALL THAT FITS');
    await page.mouse.move(480,270); pointerX=480; pointerY=270;
    await page.keyboard.press('Tab');
    await aimAt([baseCenter[0],baseCenter[1]+0.38,baseCenter[2]]);
    await page.keyboard.press('Digit3'); await page.keyboard.press('KeyX');
    await page.waitForFunction(()=>!window.__soloSurvivalState.structure_data.some(p=>p.kind==='storage'));
    await aimAt(baseCenter);
    await page.keyboard.press('KeyB'); await page.keyboard.press('Digit8');
    await page.waitForFunction(()=>window.__soloSurvivalState.build_kind==='campfire'&&window.__soloSurvivalState.placement==='');
    await attack();
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='campfire'));
    await page.keyboard.press('KeyB');
    await aimAt([baseCenter[0],baseCenter[1]+0.18,baseCenter[2]]);
    await page.keyboard.press('KeyE');
    await page.waitForFunction(()=>window.__soloSurvivalState.station!=='');
    await clickUI('DEPOSIT ALL THAT FITS');
    await clickUI('START / STOP PROCESSING');
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='campfire'&&p.inventory.some(s=>s.id==='cooked_berries')),null,{timeout:90000});
    await clickUI('START / STOP PROCESSING');
    await clickUI('TAKE ALL THAT FITS');
    await page.mouse.move(480,270); pointerX=480; pointerY=270;
    await page.keyboard.press('Tab');
    await aimAt([baseCenter[0],baseCenter[1]+0.18,baseCenter[2]]);
    await page.keyboard.press('Digit3'); await page.keyboard.press('KeyX');
    await page.waitForFunction(()=>!window.__soloSurvivalState.structure_data.some(p=>p.kind==='campfire'));
    await aimAt(baseCenter);
    await page.keyboard.press('KeyB'); await page.keyboard.press('Digit9');
    await page.waitForFunction(()=>window.__soloSurvivalState.build_kind==='furnace'&&window.__soloSurvivalState.placement==='');
    await attack();
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='furnace'));
    await page.keyboard.press('KeyB');
    await aimAt([baseCenter[0],baseCenter[1]+0.65,baseCenter[2]]);
    await page.keyboard.press('KeyE');
    await page.waitForFunction(()=>window.__soloSurvivalState.station!=='');
    await clickUI('DEPOSIT ALL THAT FITS');
    await clickUI('START / STOP PROCESSING');
    await page.waitForFunction(()=>window.__soloSurvivalState.structure_data.some(p=>p.kind==='furnace'&&p.inventory.some(s=>s.id==='metal')),null,{timeout:120000});
    await clickUI('START / STOP PROCESSING');
    await page.keyboard.press('F5');
    await page.waitForTimeout(500);
    await page.screenshot({path:'build/processing-smoke.png'});
    await page.reload({waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>window.__soloSurvivalState?.ready,null,{timeout:120000});
    const processed=await state();
    assert.ok(processed.structure_data.some(p=>p.kind==='furnace'&&!p.active&&p.inventory.some(s=>s.id==='metal')),'Smelted metal and station state restore');
    assert.ok(processed.structure_data.some(p=>p.kind==='furnace'&&p.inventory.some(s=>s.id==='cooked_berries')),'Cooked food survives transfer and save/reload');
    assert.deepEqual(errors,[],'No processing/runtime errors');
    console.log('PROCESSING_BROWSER_PASS '+JSON.stringify({structures:processed.structures,cooking:true,smelting:true,restore:true}));
  } catch (error) {
    console.log('POINTER_EVENTS '+JSON.stringify(await page.evaluate(() => window.__pointerMoves).catch(() => null)));
    console.log('FAILURE_STATE '+JSON.stringify(await page.evaluate(() => window.__soloSurvivalState).catch(() => null)));
    const shot = await page.screenshot({type:'jpeg',quality:45});
    console.log('DIAGNOSTIC_SCREENSHOT_BASE64='+shot.toString('base64'));
    throw error;
  } finally {
    if (errors.length) console.error(errors.join('\n'));
    await context.close();
    await browser.close();
  }
})().catch(e => {console.error(e);process.exitCode=1;});
